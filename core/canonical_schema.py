"""Single canonical field registry — THE Single Source of Truth.

Every module (import, mapping, validation, units, UI, export, AI) MUST
reference this registry rather than maintaining independent dictionaries.

FieldSpec contains:
- path: canonical field identifier (e.g., "mud_report.mw")
- quantity: data type for unit conversion (e.g., "density")
- unit: canonical storage unit (e.g., "ppg")
- critical: whether the field is required for valid import
- aliases: list of known header/label variations
- min_value / max_value: engineering validation bounds
- description: human-readable description
"""

from dataclasses import dataclass, field
from typing import List, Optional


@dataclass(frozen=True)
class FieldSpec:
    path: str
    quantity: str = "text"
    unit: str = ""
    critical: bool = False
    aliases: tuple = ()
    min_value: Optional[float] = None
    max_value: Optional[float] = None
    description: str = ""


