# Build the registry
FIELD_SPECS = {spec.path: spec for spec in _FIELD_DEFS}
CANONICAL_FIELDS = frozenset(FIELD_SPECS)

# Build alias → canonical field lookup (centralized, single source)
_ALIAS_LOOKUP = {}
for spec in _FIELD_DEFS:
    for alias in spec.aliases:
        normalized = alias.lower().strip()
        if normalized not in _ALIAS_LOOKUP:
            _ALIAS_LOOKUP[normalized] = spec.path

# Quantity → canonical unit lookup
_QUANTITY_UNITS = {}
for spec in _FIELD_DEFS:
    if spec.quantity and spec.unit and spec.quantity not in _QUANTITY_UNITS:
        _QUANTITY_UNITS[spec.quantity] = spec.unit


def get_critical_fields() -> frozenset:
    """Return the set of field paths that are marked critical."""
    return frozenset(path for path, spec in FIELD_SPECS.items() if spec.critical)


def get_fields_by_quantity(quantity: str) -> list:
    """Return field paths matching a given quantity type."""
    return [path for path, spec in FIELD_SPECS.items() if spec.quantity == quantity]


def get_field_spec(path: str) -> FieldSpec:
    """Get the FieldSpec for a canonical field path, or None if not found."""
    return FIELD_SPECS.get(path)


def lookup_alias(alias_text: str) -> str:
    """Look up a header/label alias and return the canonical field path.
    
    This is THE centralized alias lookup — all modules must use this
    instead of maintaining independent alias dictionaries.
    """
    normalized = alias_text.lower().strip()
    # Remove common suffixes
    cleaned = normalized.rstrip(':').strip()
    cleaned = cleaned.replace('(', '').replace(')', '').strip()
    
    # Try exact match
    result = _ALIAS_LOOKUP.get(cleaned)
    if result:
        return result
    
    # Try with common separators normalized
    for sep in ['_', '-', '/']:
        alt = cleaned.replace(sep, ' ')
        result = _ALIAS_LOOKUP.get(alt)
        if result:
            return result
    
    return ""


def get_quantity_unit(quantity: str) -> str:
    """Get the canonical unit for a quantity."""
    return _QUANTITY_UNITS.get(quantity, "")


def get_engineering_bounds(path: str):
    """Get engineering validation bounds for a field.
    
    Returns (min_value, max_value) or (None, None) if no bounds defined.
    """
    spec = FIELD_SPECS.get(path)
    if spec:
        return spec.min_value, spec.max_value
    return None, None
