    def generate(self, well_id: int, output_path: str,
                 format: str = "pdf") -> bool:
        try:
            data = self._collect_data(well_id)
            if not data:
                logger.warning(
                    f"No plan data for well {well_id}"
                )
                return False

            # ✅ اگر plan نداشته باشد
            if not data.get("plan"):
                logger.warning(
                    f"No active plan for well {well_id}"
                )
                return False

            html = self._build_html(data, selected_sections=None)

            if format == "pdf":
                return self._save_pdf(html, output_path)
            elif format == "html":
                return self._save_html(html, output_path)
            elif format == "excel":
                return self._save_excel(data, output_path, selected_sections=None)
            return False
        except Exception as e:
            logger.error(f"EOWR report error: {e}", exc_info=True)
            return False

    def _collect_data(self, well_id: int) -> dict:
        """جمع‌آوری کامل داده‌های یک چاه برای EOWR"""
        from core.database import (
            DailyReport, DrillingParameters, MudReport, BitReport,
            BHAReport, SurveyPoint, CementReport, CasingReport,
            SafetyReport, TimeLog24H, TimeLogMorning,
            LogisticsPersonnel, ServiceCompany, TransportLog,
            MaterialRequest, EquipmentLog, Section
        )
        try:
            session = self.db.create_session()
            try:
                well = self.db.get_well_by_id(well_id) or {}
                sections = self.db.get_sections_by_well(well_id) or []

                daily_reports = session.query(DailyReport).filter(
                    DailyReport.well_id == well_id
                ).order_by(DailyReport.report_date).all()

                drilling_params = session.query(DrillingParameters).filter(
                    DrillingParameters.well_id == well_id
                ).order_by(DrillingParameters.report_date).all()

                mud_reports = session.query(MudReport).filter(
                    MudReport.well_id == well_id
                ).order_by(MudReport.report_date).all()

                bit_reports = session.query(BitReport).filter(
                    BitReport.well_id == well_id
                ).order_by(BitReport.report_date).all()

                bha_reports = session.query(BHAReport).filter(
                    BHAReport.well_id == well_id
                ).order_by(BHAReport.updated_at.desc()).all()

                surveys = session.query(SurveyPoint).filter(
                    SurveyPoint.well_id == well_id
                ).order_by(SurveyPoint.md).all()

                cement_reports = session.query(CementReport).filter(
                    CementReport.well_id == well_id
                ).order_by(CementReport.report_date).all()

                casing_reports = session.query(CasingReport).filter(
                    CasingReport.well_id == well_id
                ).order_by(CasingReport.report_date).all()

                safety_reports = session.query(SafetyReport).filter(
                    SafetyReport.well_id == well_id
                ).order_by(SafetyReport.report_date).all()

                time_logs_24h = session.query(TimeLog24H).join(
                    DailyReport, TimeLog24H.report_id == DailyReport.id
                ).filter(DailyReport.well_id == well_id).all()

                time_logs_morning = session.query(TimeLogMorning).join(
                    DailyReport, TimeLogMorning.report_id == DailyReport.id
                ).filter(DailyReport.well_id == well_id).all()

                personnel = session.query(LogisticsPersonnel).filter(
                    LogisticsPersonnel.well_id == well_id
                ).all()

                services = session.query(ServiceCompany).filter(
                    ServiceCompany.well_id == well_id
                ).all()

                transport = session.query(TransportLog).filter(
                    TransportLog.well_id == well_id
                ).all()

                requests = session.query(MaterialRequest).filter(
                    MaterialRequest.well_id == well_id
                ).all()

                equipment_logs = session.query(EquipmentLog).filter(
                    EquipmentLog.well_id == well_id
                ).all()

                # Cost records اگر وجود داشته باشد
                try:
                    from core.database import CostRecord
                    cost_records = session.query(CostRecord).filter(
                        CostRecord.well_id == well_id
                    ).all()
                except Exception:
                    cost_records = []

                # Derived summaries
                total_reports = len(daily_reports)
                final_depth = max(
                    [(r.depth_2400 or 0) for r in daily_reports],
                    default=0
                )
                total_npt = sum(
                    [(l.duration or 0) for l in time_logs_24h if l.is_npt]
                )
                total_hours = sum(
                    [(l.duration or 0) for l in time_logs_24h]
                ) or 1
                npt_pct = total_npt / total_hours * 100

                avg_rop = 0
                rops = [p.avg_rop for p in drilling_params if p.avg_rop]
                if rops:
                    avg_rop = sum(rops) / len(rops)

                total_cost = 0
                if cost_records:
                    total_cost = sum([(c.actual_cost or 0) for c in cost_records])
                else:
                    # fallback تخمینی
                    total_cost = total_reports * 60000

                return {
                    "well": well,
                    "sections": sections,
                    "daily_reports": daily_reports,
                    "drilling_params": drilling_params,
                    "mud_reports": mud_reports,
                    "bit_reports": bit_reports,
                    "bha_reports": bha_reports,
                    "surveys": surveys,
                    "cement_reports": cement_reports,
                    "casing_reports": casing_reports,
                    "safety_reports": safety_reports,
                    "time_logs_24h": time_logs_24h,
                    "time_logs_morning": time_logs_morning,
                    "personnel": personnel,
                    "services": services,
                    "transport": transport,
                    "requests": requests,
                    "equipment_logs": equipment_logs,
                    "cost_records": cost_records,
                    "summary": {
                        "total_reports": total_reports,
                        "final_depth": final_depth,
                        "avg_rop": avg_rop,
                        "total_npt": total_npt,
                        "npt_pct": npt_pct,
                        "total_cost": total_cost,
                    }
                }
            finally:
                session.close()
        except Exception as e:
            logger.error(f"EOWR collect data error: {e}")
            return {}

