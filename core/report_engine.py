    def generate(self, report_id: int, output_path: str,
                 format: str = "pdf") -> bool:
        """تولید DDR"""
        try:
            data = self._collect_data(report_id)
            if not data:
                logger.error("No data for DDR")
                return False

            html = self._build_html(data)

            if format == "pdf":
                return self._save_pdf(html, output_path)
            elif format == "html":
                return self._save_html(html, output_path)
            elif format == "excel":
                return self._save_excel(data, output_path)
            return False
        except Exception as e:
            logger.error(f"DDR generation error: {e}")
            return False

    def _collect_data(self, report_id: int) -> Optional[Dict]:
        """جمع‌آوری تمام داده‌های گزارش"""
        report = self.db.get_daily_report_by_id(report_id)
        if not report:
            return None

        well_id = report.get("well_id")
        well = self.db.get_well_by_id(well_id) or {}

        # Header snapshot اگر وجود دارد
        snapshot = report.get("header_snapshot") or {}

        # Time logs
        from core.database import TimeLog24H, TimeLogMorning
        session = self.db.create_session()
        try:
            logs_24h = session.query(TimeLog24H).filter(
                TimeLog24H.report_id == report_id
            ).order_by(TimeLog24H.time_from).all()

            logs_morning = session.query(TimeLogMorning).filter(
                TimeLogMorning.report_id == report_id
            ).order_by(TimeLogMorning.time_from).all()
        finally:
            session.close()

        # Drilling params
        params = self.db.get_drilling_parameters(report_id=report_id)

        # Mud report
        mud = self.db.get_mud_report(report_id=report_id)

        # Sections
        sections = self.db.get_sections_by_well(well_id)
        current_section = None
        if report.get("section_id"):
            current_section = next(
                (s for s in sections if s["id"] == report["section_id"]),
                None
            )

        # Time analysis
        total_hrs = sum(l.duration or 0 for l in logs_24h)
        npt_hrs = sum(
            l.duration or 0 for l in logs_24h if l.is_npt
        )
        pt_hrs = total_hrs - npt_hrs

        return {
            "report": report,
            "well": well,
            "snapshot": snapshot,
            "logs_24h": logs_24h,
            "logs_morning": logs_morning,
            "params": params,
            "mud": mud,
            "section": current_section,
            "total_hrs": total_hrs,
            "npt_hrs": npt_hrs,
            "pt_hrs": pt_hrs,
        }

