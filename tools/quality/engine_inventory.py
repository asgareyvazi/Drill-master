#!/usr/bin/env python3
"""Engine inventory (M75): every calculation engine, its method label and the tests that reference it.

The inventory is generated from the source (AST only; nothing is imported or
run) so it cannot drift from the code: ``--check`` fails when
``docs/engineering/ENGINE_INVENTORY.md`` is out of date, ``--write`` refreshes it.
A test reference count is how many test files name the symbol; it shows where
evidence lives, not that a formula is validated.
"""
from __future__ import annotations

import argparse
import ast
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DOC = ROOT / "docs" / "engineering" / "ENGINE_INVENTORY.md"
ENGINES = ROOT / "core" / "engineering" / "engines"
HYDRAULICS = ROOT / "core" / "hydraulics_engine.py"
LABELS = ("SCREENING", "WORKSHEET", "TRAINING AID", "PLANNING AID")


def _tests() -> dict[str, str]:
    return {p.name: p.read_text(encoding="utf-8", errors="replace") for p in sorted((ROOT / "tests").glob("test_*.py"))}


def _referencing(symbol: str, tests: dict[str, str]) -> list[str]:
    return [name for name, body in tests.items() if symbol in body]


def _string_value(node, constants: dict[str, str]) -> str:
    if isinstance(node, ast.Constant) and isinstance(node.value, str):
        return node.value
    if isinstance(node, ast.Name):
        return constants.get(node.id, "")
    return ""


def engines() -> list[dict]:
    rows = []
    for path in sorted(ENGINES.glob("*.py")):
        if path.name == "__init__.py":
            continue
        tree = ast.parse(path.read_text(encoding="utf-8"))
        constants = {t.id: _string_value(n.value, {}) for n in tree.body if isinstance(n, ast.Assign)
                     for t in n.targets if isinstance(t, ast.Name)}
        for node in tree.body:
            if not isinstance(node, ast.ClassDef):
                continue
            method = next((_string_value(s.value, constants) for s in node.body if isinstance(s, ast.Assign)
                           and any(isinstance(t, ast.Name) and t.id == "METHOD" for t in s.targets)), "")
            if method:
                rows.append({"module": f"core/engineering/engines/{path.name}", "symbol": node.name,
                             "method": method, "labels": [lab for lab in LABELS if lab in method.upper()]})
    return rows


def hydraulics() -> list[dict]:
    tree = ast.parse(HYDRAULICS.read_text(encoding="utf-8"))
    rows = []
    for cls in (n for n in tree.body if isinstance(n, ast.ClassDef)):
        for fn in cls.body:
            if isinstance(fn, ast.FunctionDef) and not fn.name.startswith("_") and (
                    fn.name.startswith(("calc_", "calculate_", "bingham_", "power_law_"))):
                doc = (ast.get_docstring(fn) or "").strip().splitlines()
                rows.append({"module": "core/hydraulics_engine.py", "symbol": f"{cls.name}.{fn.name}",
                             "method": doc[0] if doc else "", "labels": []})
    return rows


def render() -> str:
    tests = _tests()
    lines = ["# Engine inventory", "",
             "Generated by `tools/quality/engine_inventory.py --write` from the source (AST only).",
             "`Tests` counts the test files that name the symbol: where evidence lives, not a validation",
             "claim. Labels come from the method string; an engine without a label is not thereby validated.",
             "Methods, limits and references are in `ENGINEERING_METHODS_AND_LIMITATIONS.md`.", "",
             "## Engines (`core/engineering/engines`)", "", "| Engine | Method | Labels | Tests |",
             "|---|---|---|---|"]
    for row in engines():
        refs = _referencing(row["symbol"], tests)
        lines.append(f"| `{row['symbol']}` ({row['module'].rsplit('/', 1)[-1]}) | {row['method']} | "
                     f"{', '.join(row['labels']) or '-'} | {len(refs)} |")
    lines += ["", "## Hydraulics functions (`core/hydraulics_engine.py`)", "", "| Function | First doc line | Tests |",
              "|---|---|---|"]
    for row in hydraulics():
        name = row["symbol"].split(".", 1)[1]
        refs = _referencing(name, tests)
        method = row["method"].replace("|", "/")
        if any("\u0600" <= ch <= "\u06ff" for ch in method):   # repository docs are English-only
            method = "(docstring not in English)"
        lines.append(f"| `{row['symbol']}` | {method or '-'} | {len(refs)} |")
    untested = [r["symbol"] for r in hydraulics() if not _referencing(r["symbol"].split(".", 1)[1], tests)]
    lines += ["", f"Hydraulics functions named by no test file: {len(untested)}"
              + (f" ({', '.join(f'`{u}`' for u in untested)})" if untested else ""), ""]
    return "\n".join(lines)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--write", action="store_true")
    group.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    text = render()
    if args.write:
        DOC.write_text(text, encoding="utf-8")
        print(f"wrote {DOC.relative_to(ROOT)}")
        return 0
    current = DOC.read_text(encoding="utf-8") if DOC.exists() else ""
    if current != text:
        print("ENGINE_INVENTORY.md is out of date; run tools/quality/engine_inventory.py --write")
        return 1
    print("engine inventory current")
    return 0


if __name__ == "__main__":
    sys.exit(main())
