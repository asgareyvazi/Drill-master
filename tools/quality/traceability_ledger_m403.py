#!/usr/bin/env python3
"""M403: generate the M1–M400 traceability ledger from the repository's own artefacts.

The original directives for most historical missions are not in the repository; the ledger never invents them. For
each mission N it records:

* **Directive.** Always ``UNAVAILABLE IN REPOSITORY``, because no directive text is stored. The mission report is the
  closest available record.
* **Report.** The mission report whose range covers N (``docs/mission-reports/M<a>_M<b>_*.md`` / ``M<n>_*.md``) and
  the number of times ``M<N>`` occurs in it.
* **Tests.** Test files named ``test_m<N>_*`` or ``test_m<a>_m<b>_*`` with a <= N <= b.
* **Label.** The strict label of every row that names ``M<N>`` in ``PRODUCT_CAPABILITY_MATRIX.md``,
  ``M241_CAPABILITY_INVENTORY.md`` or the M400 capability catalogue.
* **State.** The worst (most limiting) strict state among the labels of the rows whose FIRST cell names the mission
  (rows that merely cite it are counted but not used); disagreeing rows are listed in the basis column. Without a label, the state is
  ``IMPLEMENTED — PARTIALLY QUALIFIED`` when named tests exist (basis: tests only; qualification not assessed).
  Otherwise it is ``NOT VERIFIED — NO NAMED ARTEFACT``. This last value is deliberately outside the strict list: it
  marks a gap for follow-up and is not a classification.

Usage: python tools/quality/traceability_ledger_m403.py [--write | --check]
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "docs" / "engineering" / "M403_TRACEABILITY_LEDGER_M1_M400.md"
LABEL_SOURCES = ("docs/engineering/PRODUCT_CAPABILITY_MATRIX.md", "docs/engineering/M241_CAPABILITY_INVENTORY.md",
                 "docs/engineering/DRILLMASTER_COMPLETE_ENGINEERING_CAPABILITY_CATALOGUE_M400.md")
# strict states, most limiting first
STATES = (
    ("BLOCKED BY LICENSE", "BLOCKED BY LICENSE OR DATA RIGHTS"),
    ("BLOCKED BY OWNER DECISION", "BLOCKED BY OWNER DECISION"),
    ("NOT IMPLEMENTED", "NOT IMPLEMENTED"),
    ("DEPRECATED", "DEPRECATED"),
    ("DOCUMENTED ONLY", "DOCUMENTED ONLY"),
    ("READ-ONLY", "READ-ONLY"),
    ("ENGINE ONLY", "ENGINE ONLY"),
    ("UI ONLY", "UI ONLY"),
    ("NOT UI-INTEGRATED", "NOT UI-INTEGRATED"),
    ("PARTIALLY QUALIFIED", "IMPLEMENTED — PARTIALLY QUALIFIED"),
    ("QUALIFIED — SYNTHETIC", "VERIFIED COMPLETE FOR STATED SYNTHETIC SCOPE"),
)
TESTS_ONLY = "IMPLEMENTED — PARTIALLY QUALIFIED"
GAP = "NOT VERIFIED — NO NAMED ARTEFACT"


def reports():
    out = []
    for path in sorted((ROOT / "docs" / "mission-reports").glob("M*.md")):
        m = re.match(r"M(\d+)(?:_M(\d+))?_", path.name)
        if m:
            lo = int(m.group(1))
            out.append((lo, int(m.group(2) or lo), path))
    return out


def test_files():
    out = []
    for path in sorted((ROOT / "tests").glob("test_m*.py")):
        m = re.match(r"test_m(\d+)(?:_m(\d+))?[_.]", path.name)
        if m:
            lo = int(m.group(1))
            out.append((lo, int(m.group(2) or lo), path.name))
    return out


def label_rows():
    rows = []
    for rel in LABEL_SOURCES:
        path = ROOT / rel
        if path.exists():
            rows.extend((rel, line) for line in path.read_text(encoding="utf-8").splitlines() if line.startswith("|"))
    return rows


def state_of(texts):
    for needle, state in STATES:
        if any(needle in text for text in texts):
            return state
    return None


def build() -> str:
    reps, tests, rows = reports(), test_files(), label_rows()
    texts = {path: path.read_text(encoding="utf-8") for _lo, _hi, path in reps}
    lines = ["# M403 — M1–M400 traceability ledger (generated)", "",
             "Generated by `tools/quality/traceability_ledger_m403.py` (do not hand-edit). The directive text of "
             "historical missions is **not stored in the repository** and is recorded as UNAVAILABLE. The state comes "
             "from the strict labels of the capability matrix, the M241 inventory and the M400 catalogue. "
             f"`{GAP}` marks a gap for follow-up; it is not a classification. Input class: repository artefacts.", "",
             "| Mission | Directive | Report (mentions) | Named tests | Rows citing it | State | Basis |",
             "|---|---|---|---|---|---|---|"]
    counts: dict = {}
    for n in range(1, 401):
        rep = next(((p, texts[p]) for lo, hi, p in reps if lo <= n <= hi), None)
        mention = len(re.findall(rf"\bM{n}\b", rep[1])) if rep else 0
        named = [name for lo, hi, name in tests if lo <= n <= hi]
        labelled = [(src, line) for src, line in rows if re.search(rf"\bM{n}\b", line)]
        # subject rows: the mission is named in the FIRST cell (the capability), not merely cited elsewhere in the row
        subject = [line for _src, line in labelled if re.search(rf"\bM{n}\b", line.split("|")[1])]
        states = sorted({st for st in (state_of([line]) for line in subject) if st})
        state = state_of(subject)
        basis = ("strict label" + (f"; rows disagree: {' / '.join(states)}" if len(states) > 1 else "")) if state else ""
        if state is None:
            state, basis = (TESTS_ONLY, "named tests; no label (qualification not assessed)") if named else (GAP, "—")
        counts[state] = counts.get(state, 0) + 1
        report_cell = f"`{rep[0].name}` ({mention})" if rep else "none"
        tests_cell = ", ".join(f"`{t}`" for t in named[:3]) + (f" +{len(named) - 3}" if len(named) > 3 else "")
        lines.append(f"| M{n} | UNAVAILABLE IN REPOSITORY | {report_cell} | {tests_cell or '—'} | {len(labelled)} | "
                     f"{state} | {basis} |")
    lines += ["", "## Totals", "", "| State | Missions |", "|---|---|"]
    lines += [f"| {state} | {count} |" for state, count in sorted(counts.items(), key=lambda kv: -kv[1])]
    return "\n".join(lines) + "\n"


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    text = build()
    if args.write:
        OUT.write_text(text, encoding="utf-8")
    if args.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("ledger is stale: run --write", file=sys.stderr)
            return 1
    if not args.write and not args.check:
        print(text, end="")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
