def render_diagnostics_html(answer, scope_text: str = "", refinement=None) -> str:
    """How this answer was produced (M50 §9): methods, semantic availability and why, scope, passages,
    extractive vs generated, validation, conflicts and refusal.  Built only from the answer object;
    never repeats passage text.  Everything is escaped."""
    esc = html.escape
    rows = []

    def row(name, value):
        rows.append(f"<tr><td><b>{esc(name)}</b></td><td>{value}</td></tr>")

    state = STATE_STYLE.get(answer.state, (answer.state, ""))[0]
    row("Result", esc(state))
    mode = MODE_TEXT.get(answer.mode, answer.mode)
    if answer.draft:
        mode += "; the model draft failed the citation checks and was not used"
    row("Answer", esc(mode))
    retrieval = answer.retrieval
    if retrieval is not None:
        ran = [METHOD_NAMES.get(name, name) for name in retrieval.lists_used]
        row("Retrieval methods", esc(", ".join(ran) or "none ran"))
        semantic = dict(retrieval.unavailable).get("semantic")
        row("Semantic retrieval", esc("used" if "semantic" in retrieval.lists_used else
                                      (semantic or "not used")))
        scope = scope_text or retrieval.scope
        row("Search terms", esc(", ".join(ka.display_terms(retrieval.terms)) or "none"))
        if refinement:
            added, replaced = refinement
            row("Refined search", esc(f"with suggested technical terms: {', '.join(added)}"
                                      + (f"; replacing: {', '.join(replaced)}" if replaced else "")
                                      + "; same scope"))
        row("Scope", esc(f"{scope} - {retrieval.scope_documents} eligible document(s), "
                         f"{retrieval.scope_pages} reviewed page(s)"
                         + (f", page {retrieval.page_filter} only" if retrieval.page_filter else "")))
    flagged = sum(1 for e in answer.evidence if e.instruction_like or e.page_instruction_like)
    used = "Passages used" if answer.mode != "none" else "Closest passages examined (not enough to answer)"
    row(used, esc(f"{len(answer.evidence)}" + (f" ({flagged} with instruction-like text, treated as data only)"
                                               if flagged else "")))
    if answer.check is not None and answer.state in ("ready", "model_unavailable"):
        marks = " ".join(f"{ {True: '✓', False: '✗', None: '–'}[answer.check.dimensions.get(name)] }{name}"
                         for name, _ in ka.VALIDATION_DIMENSIONS)
        row("Validation", esc(f"{answer.check.label} · {ka.SEMANTIC_LABEL}") + f"<br><small>{esc(marks)}</small>")
    else:
        row("Validation", esc("not applicable - no answer was given"))
    conflicts = retrieval.conflicts if retrieval is not None else []
    if conflicts:
        labels = {f"p{e.page_id}:{e.start}-{e.end}": e.label for e in answer.evidence}
        described = []
        for conflict in conflicts:
            sides = ", ".join(f"{value:g} {conflict.unit}" + (f" [{labels[cid]}]" if cid in labels else "")
                              for value, cid in conflict.values)
            described.append(f"{conflict.quantity}: {sides}")
        row("Conflicts", "<span style=\"color:#b71c1c\">" + esc("; ".join(described)) + "</span>")
    else:
        row("Conflicts", esc("none detected among the retrieved passages"))
    if answer.mode == "none":
        missing = ka.display_terms(retrieval.missing_terms) if retrieval is not None else []
        row("Refusal", esc(answer.text + (f" Missing: {', '.join(missing)}." if missing else "")))
    if answer.model_state:
        row("Local model", esc(f"{answer.model_state}: {answer.model_message}"))
    return '<table cellspacing="2">' + "".join(rows) + "</table>"


def render_failed_draft_html(draft: str, check) -> str:
    """A model draft that failed the citation checks: shown apart, every failed dimension listed, never as
    the answer.  All document and model text is escaped."""
    rows = []
    for name, meaning in ka.VALIDATION_DIMENSIONS:
        value = check.dimensions.get(name) if check is not None else None
        mark = {True: "✓", False: "✗", None: "–"}[value]
        rows.append(f"<li>{mark} {html.escape(meaning)}</li>")
    problems = "".join(f"<li>{html.escape(p)}</li>" for p in (check.problems if check is not None else []))
    return ('<hr><p style="color:#b71c1c"><b>MODEL DRAFT NOT USED</b> - the local model\'s draft failed the '
            'citation checks, so the answer above is quoted from the documents instead.</p>'
            f'<ul>{problems}</ul><p><small>Checks:</small></p><ul>{"".join(rows)}</ul>'
            f'<p style="color:#757575"><i>Unverified model draft ({html.escape(ka.SEMANTIC_LABEL.lower())}, '
            f'citation checks failed):</i></p><p style="color:#757575">{html.escape(draft)}</p>')


def render_answer_html(text: str) -> str:
    """Escape everything, then turn [S1] / [S1, S2] into citation links."""
    blocks = []
    for line in (text or "").splitlines() or [""]:
        escaped = html.escape(line)
        escaped = _CITE.sub(lambda m: "[" + ", ".join(
            f'<a href="cite:{label.strip()}">{label.strip()}</a>' for label in re.split(r"[,،]", m.group(1))) + "]",
            escaped)
        direction = ' dir="rtl" align="right"' if _is_rtl(line) else ""
        blocks.append(f"<p{direction}>{escaped}</p>")
    return "".join(blocks)


def _dir(text: str) -> str:
    return ' dir="rtl"' if _is_rtl(text) else ' dir="ltr"'


def render_refinement_html(answer, scope_text: str = "") -> str:
    """Query refinement after insufficient evidence (M51 §7): the scope searched, the question words found
    and missing in it, the related but insufficient sources, semantic availability, and the in-scope
    technical terms to retry with.  Built from the answer object only; every term is escaped and carries
    its own direction so Persian and English terms render correctly side by side."""
    retrieval = answer.retrieval
    if answer.mode != "none" or answer.state != "no_evidence" or retrieval is None:
        return ""
    esc = html.escape

    def terms_html(terms) -> str:
        return ", ".join(f"<span{_dir(t)}>{esc(t)}</span>" for t in terms) or esc("none")

    missing = set(retrieval.missing_terms) | set(retrieval.absent_terms)
    found = ka.display_terms(t for t in retrieval.terms if t not in missing)
    lacking = ka.display_terms(t for t in retrieval.terms if t in missing)
    semantic = ("used" if "semantic" in retrieval.lists_used else
                dict(retrieval.unavailable).get("semantic") or "not available - keyword and glossary search only")
    related = [f"{e.label}: {e.file_name}, page {e.page_no}" for e in answer.evidence[:3] if e.coverage > 0]
    rows = [("Searched scope", esc(f"{scope_text or retrieval.scope} - {retrieval.scope_documents} document(s), "
                                   f"{retrieval.scope_pages} reviewed page(s)")),
            ("Found in this scope", terms_html(found)),
            ("Missing", terms_html(lacking)),
            ("Related but not sufficient", terms_html(related)),
            ("Semantic search", esc(semantic)),
            ("Suggested technical terms", terms_html(answer.suggestions) if answer.suggestions else
             esc("none - no glossary term or spelling in this scope matches the missing words"))]
    body = "".join(f"<tr><td><b>{esc(name)}</b></td><td>{value}</td></tr>" for name, value in rows)
    return f'<hr><p><b>{esc("Refine the question")}</b></p><table cellspacing="2">{body}</table>'


def _reads_on_worker(db_manager) -> bool:
    """File database: corpus reads run on a worker's own read-only connection."""
    from core.export_jobs import has_isolated_reader
    try:
        return has_isolated_reader(db_manager)
    except Exception as exc:  # silent-ok: an unknown manager is read synchronously (old behaviour)
        logger.debug("Isolated reader check failed: %s", type(exc).__name__)
        return False


def _read_corpus_on_worker(db_manager) -> "kr.CorpusSnapshot":
    from core.export_jobs import worker_database
    with worker_database(db_manager) as reader:
        return kr.read_corpus(reader)


