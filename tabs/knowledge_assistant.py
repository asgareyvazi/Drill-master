def _read_scope_rows(db_manager, kind, well_id=None, link_class=None, library_class=None) -> list:
    """Rows for one scope picker as plain dicts (M52): wells, documents or the reports of one well.

    The services are the panel's own classes, constructed on ``db_manager`` so that a worker
    reads through its own read-only connection with the same queries the GUI used before.
    """
    if kind == "wells":
        return list(link_class(db_manager).well_choices())
    if kind == "reports":
        return list(link_class(db_manager).report_choices(well_id))
    if kind == "documents":
        return list(library_class(db_manager).list_documents())
    raise ValueError(f"unknown scope list {kind!r}")


class ScopeChoicesWorker(QThread):
    """The well, document or report list for the scope pickers, read off the GUI thread (M52)."""

    done = Signal(int, str, object, object)     # token, kind, rows | None, error kind | None

    def __init__(self, token, kind, db_manager, link_class, library_class, well_id=None, parent=None):
        super().__init__(parent)
        self.token, self.kind, self.db_manager = token, kind, db_manager
        self.link_class, self.library_class, self.well_id = link_class, library_class, well_id

    def run(self):
        from core.export_jobs import worker_database
        try:
            with worker_database(self.db_manager) as reader:
                rows = _read_scope_rows(reader, self.kind, self.well_id, self.link_class, self.library_class)
        except Exception as exc:
            logger.warning("Scope list (%s) unavailable: %s", self.kind, type(exc).__name__)
            self.done.emit(self.token, self.kind, None, type(exc).__name__)
            return
        self.done.emit(self.token, self.kind, rows, None)


class AskWorker(QThread):
    """Reads the corpus (file database), builds the index if needed and answers one question."""

    stage = Signal(int, str)
    done = Signal(int, object, object)          # generation, Answer | exception text, index

    def __init__(self, generation, snapshot, index, question, scope, target, adapter, use_model, cancel, parent=None,
                 store=None, db_manager=None):
        super().__init__(parent)
        self.generation, self.snapshot, self.index = generation, snapshot, index
        self.question, self.scope, self.target = question, scope, target
        self.adapter, self.use_model, self.cancel_token, self.store = adapter, use_model, cancel, store
        self.db_manager = db_manager            # set: read the corpus here (M51)
        self.corpus_reads = 0

    def _refresh_corpus(self) -> bool:
        """One coherent read of the corpus; reuse the index when its signature still matches."""
        try:
            snapshot = _read_corpus_on_worker(self.db_manager)
            self.corpus_reads += 1
        except Exception as exc:  # an explicit read error, never "no documents"
            logger.warning("Document pages could not be read: %s", type(exc).__name__)
            self.done.emit(self.generation, f"{type(exc).__name__}: the document pages could not be read", None)
            return False
        if self.index is None or getattr(self.index, "signature", None) != snapshot.signature:
            self.snapshot, self.index = snapshot, None
        return True

    def run(self):
        if self.db_manager is not None and not self._refresh_corpus():
            return
        if self.cancel_token is not None and self.cancel_token.cancelled:
            return                              # cancelled while reading: nothing is shown
        try:
            if self.index is None:
                self.index = kr.KnowledgeIndex(self.snapshot, embedding_store=self.store,
                                               embed_model=getattr(self.adapter, "embed_model", None) or None)
            answer = ka.answer_question(self.index, self.question, self.scope, self.target, adapter=self.adapter,
                                        use_model=self.use_model, cancel=self.cancel_token,
                                        stage=lambda s: self.stage.emit(self.generation, s))
            self.done.emit(self.generation, answer, self.index)
        except Exception as exc:  # shown as an explicit error state, never as "no evidence"
            logger.warning("Knowledge Assistant question failed: %s", type(exc).__name__)
            self.done.emit(self.generation, f"{type(exc).__name__}: the question could not be answered", self.index)


